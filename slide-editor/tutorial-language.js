window.localizeTutorial = function(root, language) {
  const column = {'zh-CN':0, en:1, ja:2}[language] ?? 0;
  const copy = window.slideStudioTutorialCopy;
  // Matching stock text in any language also upgrades previously saved tutorials.
  // A user-edited text node never matches and is deliberately left alone.
  root.querySelectorAll('.slide h1,.slide h2,.slide h3,.slide p,title').forEach(el => {
    const entry = copy.find(row => row.includes(el.innerHTML));
    if (entry) el.innerHTML = entry[column];
  });
  root.querySelectorAll('.slide img[alt]').forEach(el => {
    const entry = copy.find(row => row.includes(el.getAttribute('alt')));
    if (entry) el.setAttribute('alt', entry[column]);
  });
  root.documentElement.lang = language;
};

window.localizeTutorialHTML = function(html, language) {
  const parsed = new DOMParser().parseFromString(html, 'text/html');
  window.localizeTutorial(parsed, language);
  return '<!doctype html>\n'+parsed.documentElement.outerHTML;
};
